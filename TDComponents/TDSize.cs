namespace TDComponents;

/// <summary>Tamaño de controles de formulario.</summary>
public enum TDSize
{
    /// <summary>Barras densas y acciones secundarias.</summary>
    Small,

    /// <summary>Tamaño de lectura normal. Es el valor por defecto de casi todos los controles.</summary>
    Medium,

    /// <summary>Control destacado. En <c>TDFab</c> no cambia el tamaño respecto de <c>Medium</c>.</summary>
    Large
}
